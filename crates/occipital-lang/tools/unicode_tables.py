#!/usr/bin/env python3
"""Generate Unicode 16.0 tables from verified Unicode Character Database files.

The host runtime's Unicode data APIs are not used.
"""

import argparse
import hashlib
from pathlib import Path

VERSION = "16.0.0"
INPUTS = {
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "SpecialCasing.txt": "8d5de354eef79f2395a54c9c7dcebbaf3d30fc962d0f85611ea97aa973a0c451",
    "PropList.txt": "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583",
    "DerivedCoreProperties.txt": "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd",
}
HEADER = (
    "// Generated by tools/unicode_tables.py from Unicode 16.0.0; do not edit.\n"
    "// Unicode data license: ../../unicode/LICENSE.txt\n\n"
)


def fields(text):
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            yield [part.strip() for part in data.split(";")]


def codepoints(value):
    return tuple(int(cp, 16) for cp in value.split())


def escaped(mapping):
    return '"' + "".join(f"\\u{{{cp:X}}}" for cp in mapping) + '"'


def properties(text, name):
    ranges = []
    for row in fields(text):
        if row[1] == name:
            bounds = [int(cp, 16) for cp in row[0].split("..")]
            start, end = bounds[0], bounds[-1]
            if ranges and start <= ranges[-1][1] + 1:
                assert start > ranges[-1][1], "overlapping property ranges"
                ranges[-1] = (ranges[-1][0], end)
            else:
                assert not ranges or start > ranges[-1][1], "unsorted property ranges"
                ranges.append((start, end))
    assert ranges, f"missing property: {name}"
    return ranges


def range_table(ranges):
    return HEADER + "#[rustfmt::skip]\npub(super) const RANGES: &[(u32, u32)] = &[\n" + "".join(
        f"    (0x{start:X}, 0x{end:X}),\n" for start, end in ranges
    ) + "];\n"


def case_table(mapping):
    return HEADER + "#[rustfmt::skip]\npub(super) const MAPPINGS: &[(char, &str)] = &[\n" + "".join(
        f"    ('\\u{{{cp:X}}}', {escaped(mapped)}),\n"
        for cp, mapped in sorted(mapping.items()) if mapped != (cp,)
    ) + "];\n"


def generate(text):
    upper, lower = {}, {}
    for row in fields(text["UnicodeData.txt"]):
        cp = int(row[0], 16)
        if row[12]:
            upper[cp] = codepoints(row[12])
        if row[13]:
            lower[cp] = codepoints(row[13])
    conditional = []
    for row in fields(text["SpecialCasing.txt"]):
        cp = int(row[0], 16)
        if not row[4]:
            lower[cp], upper[cp] = codepoints(row[1]), codepoints(row[3])
        elif row[4] == "Final_Sigma":
            conditional.append((cp, codepoints(row[1])))
        else:
            # Locale-tailored mappings are not part of the default full mapping.
            assert row[4].split()[0] in {"tr", "az", "lt"}, row[4]
    assert conditional == [(0x03A3, (0x03C2,))], "new language-independent context rule"
    result = {
        "upper.rs": case_table(upper),
        "lower.rs": case_table(lower) + "\n// The only locale-independent contextual mapping in SpecialCasing.txt.\n"
        + "pub(super) const FINAL_SIGMA: (char, &str) = ('\\u{3A3}', \"\\u{3C2}\");\n",
    }
    for filename, source, name in [
        ("white_space.rs", "PropList.txt", "White_Space"),
        ("bidi_control.rs", "PropList.txt", "Bidi_Control"),
        ("default_ignorable.rs", "DerivedCoreProperties.txt", "Default_Ignorable_Code_Point"),
        ("cased.rs", "DerivedCoreProperties.txt", "Cased"),
        ("case_ignorable.rs", "DerivedCoreProperties.txt", "Case_Ignorable"),
    ]:
        result[filename] = range_table(properties(text[source], name))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd", type=Path, help="directory holding the four official UCD inputs")
    parser.add_argument("--check", action="store_true", help="compare instead of writing tables")
    args = parser.parse_args()
    text = {}
    for name, expected in INPUTS.items():
        data = (args.ucd / name).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise SystemExit(f"{name}: expected SHA-256 {expected}, got {actual}")
        text[name] = data.decode("utf-8")
    destination = Path(__file__).resolve().parents[1] / "src" / "unicode"
    destination.mkdir(parents=True, exist_ok=True)
    for name, content in generate(text).items():
        path = destination / name
        data = content.encode("utf-8")
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f"generated table differs: {path}")
        else:
            path.write_bytes(data)
        print(f"{hashlib.sha256(data).hexdigest()}  {name}")
    print(f"{'Checked' if args.check else 'Generated'} 7 Unicode {VERSION} tables from 4 verified inputs")


if __name__ == "__main__":
    main()
