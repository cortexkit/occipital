#!/usr/bin/env python3
"""Generate Unicode 16 IDNA, NFC, bidi and joining tables from verified inputs.

No host Unicode database is used. See unicode/IDNA.md for input provenance.
"""

import argparse
import hashlib
from itertools import groupby
from pathlib import Path

from unicode_tables import fields, escaped

INPUTS = {
    "IdnaMappingTable.txt": "6db2ef4ed35f3b3de74ebc2e00404a9607f76d499f576b8d4043cf14f1ed175c",
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "DerivedNormalizationProps.txt": "4d4c03892dea9146d674b686e495df2d55a28d071ac474041d73518f887abddc",
    "DerivedBidiClass.txt": "71ed943a49c58568d8d92e80ecc2ba2f06e62aee9c8ebb0e6e8bd2c3ed8b180e",
    "DerivedJoiningType.txt": "6bd08b97da66b70ccfdab105a352de2984e02625239ec5695422c99b33d854f0",
}
HEADER = (
    "// Generated by tools/idna_tables.py from Unicode 16.0.0; do not edit.\n"
    "// Unicode data license: ../../../unicode/LICENSE.txt\n\n"
)


def bounds(text):
    values = [int(cp, 16) for cp in text.split("..")]
    return values[0], values[-1]


def runs(values):
    for value, group in groupby(enumerate(values), lambda item: item[1]):
        group = list(group)
        yield group[0][0], group[-1][0], value


def table(name, ty, rows):
    return f"#[rustfmt::skip]\npub(in crate::address) const {name}: &[{ty}] = &[\n" + "".join(
        f"    {row},\n" for row in rows
    ) + "];\n"


def property_table(text, default):
    # Apply @missing ranges in order, then explicit values (UAX #44).
    values = [default] * 0x110000
    for line in text.splitlines():
        if line.startswith("# @missing:"):
            span, name = line.split(":", 1)[1].split(";")
            aliases = {"Left_To_Right": "L", "Right_To_Left": "R",
                       "Arabic_Letter": "AL", "European_Terminator": "ET",
                       "Non_Joining": "U"}
            lo, hi = bounds(span.strip())
            values[lo:hi + 1] = [aliases[name.strip()]] * (hi - lo + 1)
    for row in fields(text):
        lo, hi = bounds(row[0])
        values[lo:hi + 1] = [row[1]] * (hi - lo + 1)
    return HEADER + table("RANGES", "(u32, u32, &str)", (
        f'(0x{lo:X}, 0x{hi:X}, "{value}")'
        for lo, hi, value in runs(values) if value != default
    ))


def generate(text):
    statuses = {"valid": 0, "mapped": 1, "ignored": 2, "deviation": 3, "disallowed": 4}
    mapping = []
    for row in fields(text["IdnaMappingTable.txt"]):
        lo, hi = bounds(row[0])
        mapped = tuple(int(cp, 16) for cp in row[2].split()) if len(row) > 2 else ()
        mapping.append(f"(0x{lo:X}, 0x{hi:X}, {statuses[row[1]]}, {escaped(mapped)})")
    result = {"mapping.rs": HEADER + table("ROWS", "(u32, u32, u8, &str)", mapping)}

    ccc, marks, decomposition = [0] * 0x110000, [False] * 0x110000, {}
    first = None
    for row in fields(text["UnicodeData.txt"]):
        cp = int(row[0], 16)
        if row[1].endswith(", First>"):
            first = cp
            continue
        lo = first if row[1].endswith(", Last>") else cp
        first = None
        ccc[lo:cp + 1] = [int(row[3])] * (cp - lo + 1)
        marks[lo:cp + 1] = [row[2].startswith("M")] * (cp - lo + 1)
        if row[5] and not row[5].startswith("<"):
            decomposition[cp] = tuple(int(cp, 16) for cp in row[5].split())
    excluded = set()
    for row in fields(text["DerivedNormalizationProps.txt"]):
        if row[1] == "Full_Composition_Exclusion":
            lo, hi = bounds(row[0])
            excluded.update(range(lo, hi + 1))
    compositions = sorted((parts[0], parts[1], cp) for cp, parts in decomposition.items()
                          if len(parts) == 2 and cp not in excluded)
    result["nfc.rs"] = HEADER + table("CCC", "(u32, u32, u8)", (
        f"(0x{lo:X}, 0x{hi:X}, {value})" for lo, hi, value in runs(ccc) if value
    )) + "\n" + table("MARKS", "(u32, u32)", (
        f"(0x{lo:X}, 0x{hi:X})" for lo, hi, value in runs(marks) if value
    )) + "\n" + table("DECOMPOSITION", "(u32, &str)", (
        f"(0x{cp:X}, {escaped(parts)})" for cp, parts in sorted(decomposition.items())
    )) + "\n" + table("COMPOSITION", "((u32, u32), u32)", (
        f"((0x{a:X}, 0x{b:X}), 0x{cp:X})" for a, b, cp in compositions
    ))
    result["bidi.rs"] = property_table(text["DerivedBidiClass.txt"], "L")
    result["joining.rs"] = property_table(text["DerivedJoiningType.txt"], "U")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = {}
    for name, expected in INPUTS.items():
        data = (args.inputs / name).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise SystemExit(f"{name}: expected SHA-256 {expected}, got {actual}")
        text[name] = data.decode("utf-8")
    destination = Path(__file__).resolve().parents[1] / "src" / "address" / "tables"
    destination.mkdir(parents=True, exist_ok=True)
    for name, content in generate(text).items():
        data = content.encode("utf-8")
        path = destination / name
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f"generated table differs: {path}")
        else:
            path.write_bytes(data)
        print(f"{hashlib.sha256(data).hexdigest()}  {name}")
    print(f"{'Checked' if args.check else 'Generated'} 4 Unicode 16.0.0 tables from 5 verified inputs")


if __name__ == "__main__":
    main()
