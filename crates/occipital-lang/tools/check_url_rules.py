#!/usr/bin/env python3
"""Break-check URL rules in a staged, clean build-server snapshot.

Run on the Linux build server, never concurrently with another Cargo command.
Stage the live files locally before dispatch. Each control runs all address unit tests;
exactly its named test must fail, with the other 23 passing. Originals are saved
under the job's TMPDIR and restored without writing the read-only Git index.
The build server may retain the base index rather than the local staged index,
so git diff --no-index --stat compares the saved live file to each mutant.
"""

import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path("crates/occipital-lang")
ADDRESS = "src/address.rs"
IDNA = "src/address/idna.rs"
TOKEN = "NON-VACUITY BREAK"


def case(proof, path, test, before, after):
    return (proof, path, test, [(before, after)])


CASES = [
    case("rule-1", ADDRESS, "scheme_and_absolute",
         '    } else {\n        return None;\n    };\n    let end',
         '    } else {\n        ("ftp", 21) // NON-VACUITY BREAK\n    };\n    let end'),
    case("rule-2-nontransitional", IDNA, "idna_mapping",
         '            _ => mapped.push(c),',
         '            (3, _) if c == \'ß\' => mapped.push_str("ss"), // NON-VACUITY BREAK\n            _ => mapped.push(c),'),
    case("rule-2-nfc", IDNA, "idna_nfc",
         'let normalized = normalize::nfc(&mapped);',
         'let normalized = mapped.clone(); // NON-VACUITY BREAK'),
    case("rule-2-bidi", IDNA, "idna_bidi",
         'if bidi_domain && !valid_bidi(&label) {',
         'if false && bidi_domain && !valid_bidi(&label) { // NON-VACUITY BREAK'),
    case("rule-2-joiners", IDNA, "idna_joiners",
         '    valid_joiners(&chars)', '    true // NON-VACUITY BREAK'),
    case("rule-2-hyphens", IDNA, "idna_hyphens",
         "    if first == '-'\n        || chars.last() == Some(&'-')\n        || (chars.get(2) == Some(&'-') && chars.get(3) == Some(&'-'))",
         "    if false // NON-VACUITY BREAK"),
    case("rule-2-std3", IDNA, "idna_std3",
         "|| (c.is_ascii() && !(c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'))",
         "|| (false && c.is_ascii() && !(c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')) // NON-VACUITY BREAK"),
    ("rule-2-dns", IDNA, "idna_dns_length", [
        ('if ascii.is_empty() || ascii.len() > 63 {', 'if ascii.is_empty() { // NON-VACUITY BREAK'),
        ('(output.len() <= 253).then_some(output)', 'Some(output) // NON-VACUITY BREAK'),
    ]),
    case("rule-3", ADDRESS, "host_refusals",
         'if forbidden_host(&host) {', 'if false && forbidden_host(&host) { // NON-VACUITY BREAK'),
    case("rule-4", ADDRESS, "userinfo_refused",
         "    if authority.contains('@') {\n        return None;\n    }",
         "    let authority = authority.rsplit('@').next().unwrap(); // NON-VACUITY BREAK"),
    case("rule-5-leading-zero", ADDRESS, "ports",
         "if port.starts_with('0') || !port.bytes().all(|c| c.is_ascii_digit()) {",
         "if !port.bytes().all(|c| c.is_ascii_digit()) { // NON-VACUITY BREAK"),
    case("rule-5-default", ADDRESS, "ports",
         '(port != default_port).then_some(port)', 'Some(port) // NON-VACUITY BREAK'),
    case("rule-6-malformed", ADDRESS, "escapes",
         '|| !valid_escapes(input)', '|| false // NON-VACUITY BREAK'),
    case("rule-6-hex-case", ADDRESS, "escapes",
         "output.push(bytes.next().unwrap().to_ascii_uppercase() as char);",
         "output.push(bytes.next().unwrap() as char); // NON-VACUITY BREAK"),
    case("rule-7", ADDRESS, "encoding",
         "&& !(matches!(part, Part::Query) && c == b'\\'')",
         "&& true // NON-VACUITY BREAK"),
    case("rule-8", ADDRESS, "paths",
         "if path.split('/').any(dot_segment) {",
         "if false && path.split('/').any(dot_segment) { // NON-VACUITY BREAK"),
    case("rule-9", ADDRESS, "raw_characters",
         r".any(|c| matches!(c, '\u{0}'..=' ' | '\u{7F}'..='\u{9F}' | '\\'))",
         r".any(|c| false && matches!(c, '\u{0}'..=' ' | '\u{7F}'..='\u{9F}' | '\\')) // NON-VACUITY BREAK"),
    case("rule-10-input", ADDRESS, "scalar_caps",
         'if input.chars().take(MAX_SCALARS + 1).count() > MAX_SCALARS',
         'if input.chars().take(MAX_SCALARS + 1).count() > MAX_SCALARS + 1 // NON-VACUITY BREAK'),
    case("rule-10-output", ADDRESS, "scalar_caps",
         '(output.len() <= MAX_SCALARS).then_some(output)',
         '(output.len() <= MAX_SCALARS + 10).then_some(output) // NON-VACUITY BREAK'),
    case("display", "src/text.rs", "display_escaping",
         'if needs_display_escape(c) {', 'if false && needs_display_escape(c) { // NON-VACUITY BREAK'),
]
for name in ["mapping", "nfc", "bidi", "joining"]:
    CASES.append(case(f"checksum-{name}", f"src/address/tables/{name}.rs", f"{name}_sha256",
                      "// Generated by tools/idna_tables.py from Unicode 16.0.0; do not edit.",
                      f"// Generated by tools/idna_tables.py from Unicode 16.0.0; do not edit. {TOKEN}"))


def diff(path, backup):
    result = subprocess.run(["git", "diff", "--no-index", "--stat", "--", str(backup), str(path)],
                            text=True, capture_output=True)
    assert result.returncode in (0, 1), result.stderr
    return result.stdout.strip()


def main():
    subprocess.run(["cargo", "--version"], check=True)
    evidence = []
    with tempfile.TemporaryDirectory(dir=os.environ["TMPDIR"]) as saved:
        for proof, relative, test, replacements in CASES:
            path = ROOT / relative
            original = path.read_text()
            mutated = original
            for before, after in replacements:
                assert before in mutated, (proof, before)
                mutated = mutated.replace(before, after)
            backup = Path(saved) / "original"
            shutil.copyfile(path, backup)
            assert not diff(path, backup), "saved snapshot differs from live source"
            try:
                path.write_text(mutated)
                during = diff(path, backup)
                assert during, proof
                print(f"\n{proof}: {path}\n{during}", flush=True)
                for line in mutated.splitlines():
                    if TOKEN in line:
                        print(line, flush=True)
                result = subprocess.run(["cargo", "test", "-p", "occipital-lang", "--all-features",
                                         "--lib", "address::tests"], text=True, capture_output=True)
            finally:
                shutil.copyfile(backup, path)
                path.touch()
            after = diff(path, backup)
            assert not after, after
            failed = re.findall(r"^test (\S+) \.\.\. FAILED$", result.stdout, re.M)
            expected = f"address::tests::{test}"
            summary = re.findall(r"^test result:.*$", result.stdout, re.M)
            print(f"exit={result.returncode}; failed={failed}; {summary}; restored diff=<empty>", flush=True)
            if result.returncode != 101 or failed != [expected] or not any("23 passed; 1 failed" in s for s in summary):
                print(result.stdout + result.stderr)
                raise SystemExit(f"control did not redden only {expected}")
            evidence.append(dict(proof_id=proof, obligation_id=proof.split('-')[0] + '-' + proof.split('-')[1] if proof.startswith('rule-') else proof,
                                 control=f"{relative}: {replacements[0][1].strip()}", expected_red=expected,
                                 captured_output=f"test {expected} ... FAILED\n{summary[0]}",
                                 applied_evidence=f"{path}: during: {during}; after restore: <empty>", outcome="reddened"))
    print(f"\n{len(evidence)} controls reddened exactly their named test; all other address tests passed each time")
    print(json.dumps(evidence, indent=2))


if __name__ == "__main__":
    main()
