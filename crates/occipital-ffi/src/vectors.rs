/// A `context` member for `profile`, with `registry` and `tool`.
fn context(profile: &str, registry: Json, tool: Json) -> Json {
    json!({
        "profile": profile,
        "execution_dialect": "1.0",
        "registry": registry,
        "tool": tool,
        "show_ui": {"title": "", "summary": "", "data_format": null, "data_columns": {}},
        "references": {},
        "handles": [],
    })
}

/// Records one `occ_program_check` call.
fn check(source: &[u8], ctx: &Json) -> Vector {
    let ctx = ctx.to_string();
    let ctx_c = c(&ctx);
    // SAFETY: `source` is valid for its length and `ctx_c` a live C string.
    let result = call(|out| unsafe {
        occ_program_check(source.as_ptr(), source.len(), ctx_c.as_ptr(), out)
    });
    Vector::call(
        "occ_program_check",
        json!({ "src": base64::encode(source), "ctx_json": ctx }),
        result,
    )
}

