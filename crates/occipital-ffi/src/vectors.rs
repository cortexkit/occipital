//! The FFI round-trip vectors in `vectors/ffi/`.
//!
//! Each vector file records calls made through the real entry points: the
//! exact request (the entry and its arguments) and the exact response (the
//! status and the string left in `*out`; for a reply session, the session's
//! calls in order, each recorded the same way). An app replays them through the
//! same entry points and compares what it gets byte for byte, which is how a
//! device shows it runs the same checking, evaluation and layout as Linux.
//! `README.md`, written by [`generate`] like the vectors, describes the
//! format for those replaying it.
//!
//! The cases are the inputs of every golden trace of occipital-lang that
//! these entry points can reach: the §16.8–§16.11 replies (streamed one byte
//! at a time and finished in one call) with their snapshot events and
//! measurements, the check of every §16.1–§16.7 program case and of the
//! reserved-write programs, the reserved-write replies, and standalone
//! measurement of the reply trees. While generating, each of these cases is
//! compared with its golden trace (check results, revision ids, plain text,
//! diagnostics, literals and heights), so a vector that drifted from the
//! golden inputs fails here. Two more `occ_program_check` cases, a program
//! with error diagnostics and a source with invalid UTF-8, have no golden
//! trace and are checked by assertions instead, as are the tool row cases
//! (a long command beside a Slot, evaluated and measured as a row) and the
//! version descriptor. The
//! scheduler traces drive a program session, which no entry point exposes, so
//! they have no vectors.
//!
//! `the_vectors_are_current` fails if regenerating changes any byte or adds
//! or drops a file. Run the tests with `OCCIPITAL_BLESS_VECTORS=1` to rewrite
//! the directory instead; rewritten vectors are a new recording and need
//! review before they are committed.

