/// A height as the golden traces print it (`Height`'s `Debug`).
fn golden_height(height: &Json) -> String {
    match height {
        Json::String(name) if name == "prose_deferred" => "ProseDeferred".to_owned(),
        Json::Object(known) => format!("Known(Decimal({}))", known["known"].as_str().unwrap()),
        other => panic!("unexpected height {other}"),
    }
}

/// A box state as the golden traces print it (`RenderState`'s `Debug`).
fn golden_state(state: &Json) -> String {
    match state.as_str() {
        Some("ready") => "Ready".to_owned(),
        Some("loading") => "Loading".to_owned(),
        Some("held") => "Held".to_owned(),
        Some("unavailable") => "Unavailable".to_owned(),
        _ => state.to_string(),
    }
}

/// Source spans as the golden traces print them (`Vec<SourceSpan>`'s
/// `Debug`).
fn golden_literals(literals: &Json) -> String {
    let spans: Vec<String> = literals
        .as_array()
        .unwrap()
        .iter()
        .map(|span| {
            format!(
                "SourceSpan {{ line: {}, column: {}, end_line: {}, end_column: {} }}",
                span["line"], span["column"], span["endLine"], span["endColumn"]
            )
        })
        .collect();
    format!("[{}]", spans.join(", "))
}

/// Renders a revision response, and its measurement when it was measured,
/// in the golden trace's line format. Diagnostics are written as compact
/// JSON with sorted keys, as [`golden_lines`] normalizes the golden's.
fn render_revision(lines: &mut Vec<String>, label: &str, revision: &str, measured: Option<&str>) {
    let r = json(revision);
    lines.push(format!(
        "{label}: id={} provisional={} literals={}",
        r["id"],
        r["provisional"],
        golden_literals(&r["literals"])
    ));
    for diagnostic in r["diagnostics"].as_array().unwrap() {
        lines.push(format!("  diagnostic {diagnostic}"));
    }
    lines.push(format!(
        "  plain-text={:?}",
        r["plain_text"].as_str().unwrap()
    ));
    if let Some(measured) = measured {
        let m = json(measured);
        let states: Vec<String> = m["boxes"]
            .as_array()
            .unwrap()
            .iter()
            .map(|b| golden_state(&b["state"]))
            .collect();
        lines.push(format!(
            "  measured height={} states=[{}]",
            golden_height(&m["height"]),
            states.join(", ")
        ));
    }
}

/// The lines of a golden trace that [`render_revision`] and the check
/// renderers reproduce, with each diagnostic's JSON re-encoded with sorted
/// keys.
fn golden_lines(trace: &str) -> Vec<String> {
    const KEPT: [&str; 9] = [
        "example=",
        "check=",
        "profile=",
        "  check=",
        "streamed one byte at a time:",
        "final: ",
        "snapshot",
        "  plain-text=",
        "  measured height=",
    ];
    trace
        .lines()
        .filter_map(|line| {
            if let Some(diagnostic) = line.strip_prefix("  diagnostic ") {
                let value: Json = serde_json::from_str(diagnostic).unwrap();
                return Some(format!("  diagnostic {value}"));
            }
            KEPT.iter()
                .any(|prefix| line.starts_with(prefix))
                .then(|| line.to_owned())
        })
        .collect()
}

/// `text` with every `id=<digits>` written as `id=_`, for comparing a
/// one-shot reply with a streamed golden: streaming publishes provisional
/// revisions first, so only the ids differ.
fn without_ids(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(at) = rest.find("id=") {
        out.push_str(&rest[..at + 3]);
        rest = rest[at + 3..].trim_start_matches(|c: char| c.is_ascii_digit());
        out.push('_');
    }
    out.push_str(rest);
    out
}

/// Runs a reply trace through a recorded session, streamed one byte per
/// chunk or finished in one call, and compares it with its golden trace.
/// Returns the session vector, the last committed tree and the height of
/// its measurement.
fn reply(case: &ReplyCase, streamed: bool) -> (Vector, Tree, Json) {
    let mut s = Session::new();
    let mut lines = vec![format!("example={} profile=reply", case.name)];
    let revision = if streamed {
        let mut provisional = 0;
        for byte in case.source.as_bytes() {
            if s.chunk(slice::from_ref(byte)) != "null" {
                provisional += 1;
            }
        }
        lines.push(format!(
            "streamed one byte at a time: provisional={provisional}"
        ));
        s.finish(&[], &case.records)
    } else {
        s.finish(case.source.as_bytes(), &case.records)
    };
    let mut measured = s.measure();
    render_revision(&mut lines, "final", &revision, Some(&measured));
    for (n, bytes) in &case.snapshots {
        lines.push(format!("snapshot $$tc({n}) bytes={bytes:?}"));
        let event = json!({
            "kind": "snapshot",
            "reference": n,
            "result": {"ok": base64::encode(bytes.as_bytes())},
        })
        .to_string();
        let revision = s.event(&event);
        measured = s.measure();
        render_revision(
            &mut lines,
            &format!("snapshot-{n}"),
            &revision,
            Some(&measured),
        );
    }
    let mut golden = golden_lines(case.trace);
    if streamed {
        assert_eq!(lines, golden, "{} streamed", case.name);
    } else {
        golden.retain(|line| !line.starts_with("streamed one byte"));
        let strip = |lines: &[String]| lines.iter().map(|l| without_ids(l)).collect::<Vec<_>>();
        assert_eq!(strip(&lines), strip(&golden), "{} one-shot", case.name);
    }
    let tree = s.committed_tree();
    (s.into_vector(), tree, json(&measured)["height"].clone())
}

