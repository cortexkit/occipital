/// One recorded call, or for a reply session the session.
#[derive(Serialize)]
struct Vector {
    entry: &'static str,
    request: Json,
    status: i32,
    response: Response,
}

#[derive(Serialize)]
#[serde(untagged)]
enum Response {
    /// The string an entry left in `*out`, or `null` for NULL.
    Out(Option<String>),
    /// The calls made on a reply session.
    Calls(Vec<Vector>),
}

impl Vector {
    fn call(entry: &'static str, request: Json, (status, out): (i32, Option<String>)) -> Self {
        Self {
            entry,
            request,
            status,
            response: Response::Out(out),
        }
    }

    /// The response string of an `OCC_OK` call.
    fn ok(&self) -> &str {
        assert_eq!(self.status, OCC_OK, "{}: {}", self.entry, self.request);
        match &self.response {
            Response::Out(Some(out)) => out,
            _ => panic!("{} left *out NULL", self.entry),
        }
    }
}

/// A reply session whose every call is recorded.
struct Session {
    reply: *mut OccReply,
    calls: Vec<Vector>,
}

impl Session {
    /// A session as the golden traces make one: the reply dialect, a
    /// 320-point page layout and fresh chat and app accounts.
    fn new() -> Self {
        let (chat, app) = (account(0), account(1));
        let (stamp, layout) = (c(STAMP), c(LAYOUT));
        let (status, reply) = new_reply_raw(stamp.as_ptr(), layout.as_ptr(), chat, app);
        // SAFETY: both handles are live and freed exactly once.
        unsafe {
            occ_account_free(chat);
            occ_account_free(app);
        }
        assert_eq!(status, OCC_OK);
        Self {
            reply,
            calls: vec![],
        }
    }

    /// Records a call that must succeed and returns its response.
    fn record(
        &mut self,
        entry: &'static str,
        request: Json,
        result: (i32, Option<String>),
    ) -> String {
        let vector = Vector::call(entry, request, result);
        let out = vector.ok().to_owned();
        self.calls.push(vector);
        out
    }

    fn chunk(&mut self, bytes: &[u8]) -> String {
        let reply = self.reply;
        // SAFETY: `reply` is live and `bytes` valid for its length.
        let result =
            call(|out| unsafe { occ_reply_chunk(reply, bytes.as_ptr(), bytes.len(), out) });
        self.record(
            "occ_reply_chunk",
            json!({ "bytes": base64::encode(bytes) }),
            result,
        )
    }

    fn finish(&mut self, tail: &[u8], records: &str) -> String {
        let reply = self.reply;
        let records_c = c(records);
        // SAFETY: `reply` is live, `tail` valid for its length and
        // `records_c` a live C string.
        let result = call(|out| unsafe {
            occ_reply_finish(reply, tail.as_ptr(), tail.len(), records_c.as_ptr(), out)
        });
        self.record(
            "occ_reply_finish",
            json!({ "tail": base64::encode(tail), "records_json": records }),
            result,
        )
    }

    fn event(&mut self, event: &str) -> String {
        let reply = self.reply;
        let event_c = c(event);
        // SAFETY: `reply` is live and `event_c` a live C string.
        let result = call(|out| unsafe { occ_reply_event(reply, event_c.as_ptr(), out) });
        self.record("occ_reply_event", json!({ "event_json": event }), result)
    }

    /// Measures the current candidate with the fixed metrics, which commits it.
    fn measure(&mut self) -> String {
        let reply = self.reply;
        let layout = c(LAYOUT);
        let mut script = Script::default();
        let metrics = table(&mut script);
        // SAFETY: `reply` is live, `layout` a live C string and `metrics` a
        // live table over a live script.
        let result =
            call(|out| unsafe { occ_reply_measure(reply, layout.as_ptr(), &metrics, out) });
        self.record(
            "occ_reply_measure",
            json!({ "layout_json": LAYOUT, "metrics": METRICS }),
            result,
        )
    }

    /// The tree of the session's committed revision.
    fn committed_tree(&self) -> Tree {
        // SAFETY: `reply` is live and no entry is running on it.
        let session = &unsafe { &*self.reply }.session;
        (*session.committed.as_ref().unwrap().0.tree).clone()
    }

    /// Frees the session and returns it as an `occ_reply_new` vector.
    fn into_vector(self) -> Vector {
        // SAFETY: `reply` is live and freed exactly once.
        unsafe { occ_reply_free(self.reply) };
        Vector {
            entry: "occ_reply_new",
            request: json!({ "stamp_json": STAMP, "layout_json": LAYOUT, "chat": 0, "app": 1 }),
            status: OCC_OK,
            response: Response::Calls(self.calls),
        }
    }
}

/// The resolved reference record the reply traces stamp for every N.
fn reference_record() -> Json {
    json!({"state": "resolved", "reason": null, "tool": "bash", "bytes": 20, "call_key": "call"})
}

/// `records_json` with `references` resolved and `handles`.
fn records(references: &[u64], handles: Json) -> String {
    let references: serde_json::Map<String, Json> = references
        .iter()
        .map(|n| (n.to_string(), reference_record()))
        .collect();
    json!({ "references": references, "handles": handles }).to_string()
}

